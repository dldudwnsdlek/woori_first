// 발표자 노트 문자열
function notesOf(s) {
  const mm = (t) => `${Math.floor(t / 60)}:${String(t % 60).padStart(2, "0")}`;
  const lines = [`[${s.no}/10] ${s.title} · 배정 ${mm(s.sec)}`, ""];
  let click = 0;
  for (const seg of s.segments) {
    if (seg.cue) {
      click += 1;
      lines.push(`▶ 클릭 ${click} — ${seg.cue}`);
    }
    lines.push(seg.text, "");
  }
  lines.push(`[전환] ${s.transition}`);
  return lines.join("\n");
}
SLIDES.forEach((s) => (s.notes = notesOf(s)));

